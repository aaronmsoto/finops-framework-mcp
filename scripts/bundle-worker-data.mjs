#!/usr/bin/env node
// Build-time data bundler for the Cloudflare Worker (T-037,
// .agents/specs/focus-mcp-v1.md "Packaging / worker / demo"). The worker is
// stateless and must never touch node:fs at runtime, so the framework and
// FOCUS artifacts are assembled and ajv-validated here (reusing the same
// loadArtifact/loadFocusStore seam the stdio servers use — same schemas,
// same manifest sha256 checks) and re-emitted as plain TypeScript modules
// under src/workers/generated/ that `import default` the data as object
// literals. FocusStore's two Map fields are serialized as plain objects
// (rehydrated into Maps at request time by src/workers/data.ts) since Maps
// aren't JSON-representable. Requires a prior `npm run build` (loads the
// compiled loaders from dist/shared/, like scripts/bundle-focus-samples.mjs
// does for the crawler seam).

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";
import { loadArtifact, loadFocusStore } from "../dist/shared/index.js";

const ROOT = join(import.meta.dirname, "..");
const OUT_DIR = join(ROOT, "src/workers/generated");

function ensureBuilt() {
  const sharedIndex = join(ROOT, "dist/shared/index.js");
  if (!existsSync(sharedIndex)) {
    execFileSync("npm", ["run", "build"], { cwd: ROOT, stdio: "inherit" });
  }
}

function writeModule(relPath, typeImport, typeName, valueName, value) {
  const json = JSON.stringify(value, null, 2);
  const content =
    `// GENERATED by scripts/bundle-worker-data.mjs — do not hand-edit.\n` +
    `// Re-run "node scripts/bundle-worker-data.mjs" after data/ changes.\n` +
    `${typeImport}\n\n` +
    `const ${valueName}: ${typeName} = ${json};\n\n` +
    `export default ${valueName};\n`;
  writeFileSync(join(OUT_DIR, relPath), content, "utf8");
}

function bundleFramework() {
  const artifact = loadArtifact(join(ROOT, "data/framework"));
  writeModule(
    "framework-artifact.ts",
    'import type { Artifact } from "../../shared/types.js";',
    "Artifact",
    "frameworkArtifact",
    artifact,
  );
  console.error("bundle-worker-data: wrote framework-artifact.ts");
}

function bundleFocus() {
  const store = loadFocusStore(join(ROOT, "data/focus"));
  const serialized = {
    index: store.index,
    versions: Object.fromEntries(store.versions),
    diff: store.diff,
    kpiMapping: store.kpiMapping,
    sampleManifest: store.sampleManifest,
    sampleCsv: Object.fromEntries(store.sampleCsv),
  };
  writeModule(
    "focus-store.ts",
    'import type { SerializedFocusStore } from "../data.js";',
    "SerializedFocusStore",
    "focusStore",
    serialized,
  );
  console.error("bundle-worker-data: wrote focus-store.ts");
}

ensureBuilt();
mkdirSync(OUT_DIR, { recursive: true });
bundleFramework();
bundleFocus();

// Keep the committed output gate-clean (format gate: prettier --check)
// regardless of who re-runs this script.
execFileSync(
  "npx",
  [
    "prettier",
    "--write",
    join(OUT_DIR, "framework-artifact.ts"),
    join(OUT_DIR, "focus-store.ts"),
  ],
  { cwd: ROOT, stdio: "inherit" },
);
