export interface CompiledSurface {
  /** Repo-relative path. */
  relPath: string;
  content: string;
  /** chmod applied on write (copilot.sh is 755). */
  mode?: number;
}

/**
 * Compile every enforcement surface in memory (settings merge uses the file
 * currently on disk). The list is mode-dependent: branching.mode
 * "integration" adds a fifth surface, the integration-branch ruleset.
 */
export function compileSurfaces(rootDir: string, policy: ApprovalsPolicy): CompiledSurface[] {
  const settingsPath = path.join(rootDir, ".claude", "settings.json");
  const surfaces: CompiledSurface[] = [
    { relPath: ".claude/settings.json", content: compileSettingsJson(policy, readTextIfExists(settingsPath)) },
    { relPath: "scripts/copilot.sh", content: compileCopilotWrapper(policy), mode: 0o755 },
    { relPath: ".github/CODEOWNERS", content: compileCodeowners(policy) },
    { relPath: ".github/rulesets/main-branch.json", content: compileRuleset(policy) },
  ];
  if (policy.branching.mode === "integration") {
    surfaces.push({ relPath: INTEGRATION_RULESET_PATH, content: compileIntegrationRuleset(policy) });
  }
  return surfaces;
}

/**
 * Write every surface for the current mode. In trunk mode a leftover
 * integration-branch ruleset (from a previous integration-mode compile) is
 * REMOVED, so flipping modes back cleans up. Returns the repo-relative paths
 * written.
 */
export function compileApprovals(rootDir: string, policy: ApprovalsPolicy): string[] {
  const written: string[] = [];
  for (const surface of compileSurfaces(rootDir, policy)) {
    const abs = path.join(rootDir, surface.relPath);
    ensureDir(path.dirname(abs));
    fs.writeFileSync(abs, surface.content);
    if (surface.mode !== undefined) fs.chmodSync(abs, surface.mode);
    written.push(surface.relPath);
  }
  if (policy.branching.mode !== "integration") {
    fs.rmSync(path.join(rootDir, INTEGRATION_RULESET_PATH), { force: true });
  }
  return written;
}

export interface DriftReport {
  ok: boolean;
  drifted: Array<{ path: string; reason: "missing" | "differs" | "stale" }>;
}

/**
 * Recompile in memory and diff against the files on disk. Missing generated
 * files count as drift; in trunk mode an EXISTING integration-branch ruleset
 * is drift too (reason "stale" — `approvals compile` removes it). Exit 1 on
 * any drift (CI runs this).
 */
export function checkApprovals(rootDir: string, policy: ApprovalsPolicy): DriftReport {
  const drifted: DriftReport["drifted"] = [];
  for (const surface of compileSurfaces(rootDir, policy)) {
    const onDisk = readTextIfExists(path.join(rootDir, surface.relPath));
    if (onDisk === null) drifted.push({ path: surface.relPath, reason: "missing" });
    else if (onDisk !== surface.content) drifted.push({ path: surface.relPath, reason: "differs" });
  }
  if (policy.branching.mode !== "integration" && fs.existsSync(path.join(rootDir, INTEGRATION_RULESET_PATH))) {
    drifted.push({ path: INTEGRATION_RULESET_PATH, reason: "stale" });
  }
  return { ok: drifted.length === 0, drifted };
}
